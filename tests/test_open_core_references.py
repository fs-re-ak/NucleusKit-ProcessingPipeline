"""Nucleus-Kit gives exactly re-ak-core's outputs (open-core Phase 4).

Since 2.0.0 the processing is re-ak-core's default pipeline; Nucleus-Kit only adds local steps
(video rotation, GPS) that write no processing output. This test runs Nucleus-Kit and
``reak_core.pipeline.Pipeline.default()`` on the same deterministic synthetic sessions generated by
``re-ak-core/tests/synthetic`` and checks that every processing output is identical. The values
themselves are checked against the references by re-ak-core's own tests.

Needs a ``re-ak-core`` checkout next to this repository (or ``RE_AK_CORE=<path>``) for the synthetic
generator; skipped otherwise. Runs two cases by default; set ``RE_AK_REFERENCE_CASES=all`` or a
comma-separated list for more.
"""

from __future__ import annotations

import json
import os
import shutil
import sys

import pytest

_REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_CORE = os.environ.get("RE_AK_CORE", os.path.join(os.path.dirname(_REPO), "re-ak-core"))
_DEFAULT_CASES = ["baseline", "emg_rms_threshold"]

pytestmark = pytest.mark.skipif(
    not os.path.isfile(os.path.join(_CORE, "tools", "refkit.py")),
    reason="re-ak-core checkout not found (set RE_AK_CORE)",
)


def _refkit():
    sys.path.insert(0, os.path.join(_CORE, "tools"))
    import refkit

    return refkit


def _cases() -> list[str]:
    wanted = os.environ.get("RE_AK_REFERENCE_CASES", "")
    if wanted == "all":
        return [c.name for c in _refkit().CASES]
    return wanted.split(",") if wanted else _DEFAULT_CASES


# Every processing output, except metainfo.json and processing.json (paths and run times).
_OUTPUTS = (
    "results/Emotions.csv",
    "results/emotion_model.json",
    "results/Cognition.csv",
    "results/Arousal.csv",
    "results/HeartDynamics.csv",
    "features/emotions/avgRms.csv",
    "features/emotions/rmsSignals.csv",
    "features/emotions/emotionClassifierInputs.csv",
    "features/emotions/relabeled-samples.csv",
    "features/cognition/powerBands.csv",
    "features/cognition/artefactStats.csv",
    "features/cognition/epochMetrics.csv",
    "features/eda/SCR_events.csv",
    "features/ppg/ppg_resampled.csv",
    "features/events/processedFeatureEvents.csv",
)
_ANNOTATIONS = "features/events/playback_annotations.json"


def _annotations_without_ids(root: str):
    """Playback annotations with their random ``id`` fields removed (``None`` when not written)."""
    path = os.path.join(root, _ANNOTATIONS)
    if not os.path.isfile(path):
        return None
    with open(path, encoding="utf-8") as fh:
        doc = json.load(fh)

    def strip(value):
        if isinstance(value, dict):
            return {k: strip(v) for k, v in value.items() if k != "id"}
        if isinstance(value, list):
            return [strip(v) for v in value]
        return value

    return strip(doc)


@pytest.mark.parametrize("case", _cases())
def test_nucleuskit_outputs_equal_core_outputs(case: str, tmp_path) -> None:
    from nucleuskit_toolkit.pipeline import NucleusKitProcessingToolkit
    from nucleuskit_toolkit.session_job import session_job_from_folder
    from reak_core.pipeline import Pipeline

    refkit = _refkit()
    nk_root = str(tmp_path / "nk" / case)
    core_root = str(tmp_path / "core" / case)
    refkit.generate(case, nk_root)
    shutil.copytree(nk_root, core_root)

    NucleusKitProcessingToolkit(None).processSession(session_job_from_folder(nk_root))
    Pipeline.default().run(core_root)

    present = [rel for rel in _OUTPUTS if os.path.isfile(os.path.join(core_root, rel))]
    assert "results/Emotions.csv" in present
    diffs = refkit.compare_dirs(nk_root, core_root, rtol=0.0, atol=0.0, outputs=tuple(present))
    report = "\n".join(f"{d.output}: {d.detail}" for d in diffs)
    assert not diffs, f"Nucleus-Kit outputs differ from re-ak-core's:\n{report}"
    assert _annotations_without_ids(nk_root) == _annotations_without_ids(core_root)
